print("=== โปรแกรมคำนวณพื้นที่รูปทรง ===")
print("1. สี่เหลี่ยมผืนผ้า")
print("2. สามเหลี่ยม")
print("3. วงกลม")

เลือก = input("เลือกหมายเลขรูปทรง: ")

if เลือก == "1":
    กว้าง = float(input("ป้อนความกว้าง: "))
    ยาว = float(input("ป้อนความยาว: "))
    พื้นที่ = กว้าง * ยาว

elif เลือก == "2":
    ฐาน = float(input("ป้อนฐาน: "))
    สูง = float(input("ป้อนความสูง: "))
    พื้นที่ = 0.5 * ฐาน * สูง

elif เลือก == "3":
    รัศมี = float(input("ป้อนรัศมี: "))
    พื้นที่ = 3.14 * รัศมี ** 2

else:
    print("เลือกไม่ถูกต้อง")
    exit()

print("พื้นที่ =", round(พื้นที่, 2), "ตารางหน่วย")